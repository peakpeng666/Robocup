#!/usr/bin/env python3
"""Generate an *additive* B-Human source patch: module ForgeWalkingEngine.

The module is a renamed copy of the official WalkingEngine (identical observation encoding,
network call and action decoding) plus one experimental motion-control knob:

    walkNeuronalNetworkParameters.actionFilterAlpha  (default 0)
    target_t = alpha * target_{t-1} + (1 - alpha) * decoded_policy_target_t   for the 12 leg joints

With alpha = 0 the arithmetic is the official one. The patch only adds new files, so the
official WalkingEngine stays in the binary unchanged; a team selects the module through its
own scenario threads.cfg (providers of WalkGenerator/StandGenerator/WalkStepData/
WalkingEngineOutput). At construction the module prints an ``AUDIT forge_module`` line so a
match can prove which robots ran it.

Usage: make_forge_walking_engine_patch.py OUTPUT.patch
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "bhuman/local-k1-validation-20261019/bhuman-local/Src/Modules/MotionControl/WalkingEngine"
TARGET_DIR = "Src/Modules/MotionControl/ForgeWalkingEngine"
RENAMES = ["WalkingEngineBase", "WalkingEngine", "ArmParameters", "WalkTargetScaling", "CommonSpeedParameters",
           "StepSizeParameters", "TranslationPolygonParameters", "ConfiguredParameters", "FrequencyParameters",
           "BallNetworkParameters", "WalkNeuronalNetworkParameters", "DummyPhase", "WalkPhase"]


def rename(text: str) -> str:
    for name in RENAMES:
        text = re.sub(rf"\b{name}\b", "Forge" + name, text)
    return text


def must_replace(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(f"anchor not found exactly once: {old[:80]!r}")
    return text.replace(old, new)


def header() -> str:
    text = rename((SOURCE / "WalkingEngine.h").read_text())
    text = must_replace(text, "  (Pose2f) slowWalkStepSpeed, /**< Speed values to classify slow walking. This is based on the step size. */\n",
                        "  (Pose2f) slowWalkStepSpeed, /**< Speed values to classify slow walking. This is based on the step size. */\n"
                        "  (float)(0.f) actionFilterAlpha, /**< Forge: EMA weight of the previous leg target (0 = official behaviour). */\n")
    return "// Generated by forge/tools/make_forge_walking_engine_patch.py from the official WalkingEngine.h.\n" + text


def source() -> str:
    text = rename((SOURCE / "WalkingEngine.cpp").read_text())
    text = must_replace(text, '#include "ForgeWalkingEngine.h"\n',
                        '#include "ForgeWalkingEngine.h"\n#include <cmath>\n#include <cstdio>\n#include <cstdlib>\n')
    decode = ("    const float* output = engine.walkPolicy.output(0).data();\n"
              "    for(Joints::Joint j : jointList)\n"
              "      target.angles[j] = engine.walkNeuronalNetworkParameters.actionClipRange.limit(*output++) + engine.offset.angles[j];\n")
    filtered = ("    const JointAngles forgePreviousTarget = target;\n" + decode +
                "    const float forgeAlpha = engine.walkNeuronalNetworkParameters.actionFilterAlpha;\n"
                "    if(forgeAlpha > 0.f)\n"
                "      for(Joints::Joint j : jointList)\n"
                "        if(forgePreviousTarget.angles[j] != JointAngles::off && forgePreviousTarget.angles[j] != JointAngles::ignore &&\n"
                "           std::isfinite(static_cast<float>(forgePreviousTarget.angles[j])))\n"
                "          target.angles[j] = forgeAlpha * static_cast<float>(forgePreviousTarget.angles[j]) +\n"
                "                             (1.f - forgeAlpha) * static_cast<float>(target.angles[j]);\n")
    text = must_replace(text, decode, filtered)
    constructor = "{\n  compile();\n"
    audit = ("{\n  compile();\n"
             "  if(std::getenv(\"BH_AUDIT\"))\n"
             "    std::fprintf(stderr, \"AUDIT forge_module name=ForgeWalkingEngine team=%d player=%d alpha=%.4f model=%s\\n\",\n"
             "                 Global::getSettings().teamNumber, Global::getSettings().playerNumber,\n"
             "                 walkNeuronalNetworkParameters.actionFilterAlpha, walkNeuronalNetworkParameters.modelName.c_str());\n")
    text = must_replace(text, constructor, audit)
    return "// Generated by forge/tools/make_forge_walking_engine_patch.py from the official WalkingEngine.cpp.\n" + text


def new_file_patch(path: str, content: str) -> str:
    lines = content.splitlines()
    body = "".join("+" + line + "\n" for line in lines)
    return (f"diff --git a/{path} b/{path}\nnew file mode 100644\n--- /dev/null\n+++ b/{path}\n"
            f"@@ -0,0 +1,{len(lines)} @@\n{body}")


def main():
    out = Path(sys.argv[1])
    patch = new_file_patch(f"{TARGET_DIR}/ForgeWalkingEngine.h", header()) + \
        new_file_patch(f"{TARGET_DIR}/ForgeWalkingEngine.cpp", source())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(patch)
    print(out, len(patch.splitlines()), "lines")


if __name__ == "__main__":
    main()
